static DIR: OnceLock<PathBuf> = OnceLock::new();

pub fn use_pipeline_cache(dir: PathBuf) {
    let _ = DIR.set(dir);
}

pub(crate) static MADE: AtomicU64 = AtomicU64::new(0);
